/* ========================================
   FORMAT DASHBOARD STATS
======================================== */
const numberFormatter = new Intl.NumberFormat('he-IL');
const formatNextAppointment = (appointment) => {
  if (!appointment?.date || !appointment?.time) {
    return 'אין תור קרוב';
  }
  const date = new Date(appointment.date);
  if (Number.isNaN(date.getTime())) {
    return 'אין תור קרוב';
  }
  const formattedDate = new Intl.DateTimeFormat('he-IL', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    timeZone: 'UTC',
  }).format(date);
  return `${formattedDate} • ${appointment.time}`;
};
export const buildDashboardStats = (config, stats = {}) => {
  return config.map((item) => {
    const { suffix, ...card } = item;
    const rawValue = stats[item._id];
    if (item._id === 'nextAppointment') {
      return {
        ...card,
        value: formatNextAppointment(rawValue),
      };
    }
    return {
      ...card,
      value: typeof rawValue === 'number' ? `${numberFormatter.format(rawValue)} ${suffix || ''}`.trim() : '—',
    };
  });
};
